const MONTHS: Record<string, string> = {
  January: "enero", February: "febrero", March: "marzo", April: "abril", May: "mayo", June: "junio", July: "julio", August: "agosto", September: "septiembre", October: "octubre", November: "noviembre", December: "diciembre",
  Jan: "ene", Feb: "feb", Mar: "mar", Apr: "abr", Jun: "jun", Jul: "jul", Aug: "ago", Sep: "sept", Oct: "oct", Nov: "nov", Dec: "dic",
};
const DAYS: Record<string, string> = {
  Monday: "lunes", Tuesday: "martes", Wednesday: "miércoles", Thursday: "jueves", Friday: "viernes", Saturday: "sábado", Sunday: "domingo",
  Mon: "lun", Tue: "mar", Wed: "mié", Thu: "jue", Fri: "vie", Sat: "sáb", Sun: "dom",
};
const DATE_WORD = new RegExp(`\\b(${[...Object.keys(MONTHS), ...Object.keys(DAYS)].join("|")})\\b`, "g");

/** "Mon, Nov 30" → "lun, 30 nov"; "Thursday, November 5" → "jueves, 5 noviembre". Only for text that is just a date. */
function date(s: string): string | null {
  if (!/^[A-Za-z]{3,9},?\s+[A-Za-z]{3,9}\s+\d{1,2}(,\s*\d{4})?$|^[A-Za-z]{3,9}\s+\d{1,2}(,\s*\d{2,4})?$|^[A-Za-z]{3,9}\s+'?\d{2,4}$|^[A-Za-z]{3,9}$/.test(s)) return null;
  const words = s.match(/[A-Za-z]+/g) ?? [];
  if (!words.every((w) => MONTHS[w] || DAYS[w])) return null;
  return s.replace(/([A-Za-z]{3,9})\s+(\d{1,2})(?!\d)/, "$2 $1").replace(DATE_WORD, (w) => MONTHS[w] ?? DAYS[w]);
}

